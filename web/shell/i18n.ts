export const DICTIONARIES: Record<string, Dictionary> = { en, ja, "zh-Hans": zhHans };

// `{name}` in a phrase is replaced by vars.name.
export function t(key: string, vars: Record<string, string | number> = {}) {
  const phrase = DICTIONARIES[language()]?.[key] ?? en[key] ?? key;
  return phrase.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}
